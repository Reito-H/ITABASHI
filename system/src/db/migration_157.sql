-- ===================================================
-- migration_157: 異常気象警報 注意喚起サイネージ ― 発令記録を日付ベースに変更
--
--   weather_notice_alerts（migration_156）は「警報名＋既定の注意文言」のテンプレート辞書として残す。
--   実際の発令は「いつ・どの警報が・どのエリアで発令されたか」を1件ずつ日付付きで記録する
--   weather_notice_events を新設し、サイネージは「本日(event_date=今日)」の記録だけを表示する。
--   1件の記録につき「日付＋警報名の見出しスライド」→「注意文言スライド」の2枚を約10秒（5秒×2枚）で表示し、
--   本日分の記録が複数あれば順番に繰り返す。
--
--   過去分（国際自動車 km第187号の不利益処分通知に記載の実績）を参考データとして先行登録する。
-- ===================================================

CREATE TABLE IF NOT EXISTS weather_notice_events (
  id            INTEGER PRIMARY KEY AUTOINCREMENT,
  event_date    TEXT NOT NULL,             -- 発令日 'YYYY-MM-DD'
  warning_name  TEXT NOT NULL DEFAULT '',  -- 警報名（例: 大雨警報）
  area          TEXT,                      -- 対象エリア（例: 23区東部、23区西部）任意
  caution_text  TEXT NOT NULL DEFAULT '',
  sort_order    INTEGER NOT NULL DEFAULT 0,
  created_at    TEXT DEFAULT (datetime('now','localtime')),
  updated_at    TEXT DEFAULT (datetime('now','localtime'))
);
CREATE INDEX IF NOT EXISTS idx_weather_notice_events_date ON weather_notice_events(event_date, sort_order);

