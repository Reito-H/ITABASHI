// ---- レンダリング -------------------------------------------------------

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

export function tutorialImgUrl(name: string): string {
  return `${A}/settings/tutorial/img/${name}.webp`;
}

function renderFigure(f: TutFigure): string {
  const marks = (f.marks ?? []).map(m => `<li><span class="tut-mk">${m.n}</span><span>${esc(m.text)}</span></li>`).join('');
  return `<figure class="tut-fig${f.narrow ? ' tut-fig-narrow' : ''}">
    <img src="${tutorialImgUrl(f.img)}" alt="${esc(f.caption ?? f.img)}" loading="lazy" decoding="async">
    ${f.caption ? `<figcaption>${esc(f.caption)}</figcaption>` : ''}
    ${marks ? `<ol class="tut-marks">${marks}</ol>` : ''}
  </figure>`;
}

function renderSection(sec: TutSection, chapterNo: number, secNo: number): string {
  const permAttr = sec.perm ? ` data-perm-key="${esc(sec.perm)}"` : '';
  const keywords = esc([sec.title, sec.lead, ...(sec.tasks ?? []), ...(sec.can ?? [])].join(' '));
  return `<div class="tut-section" id="sec-${sec.id}"${permAttr} data-keywords="${keywords}">
    <h3><span class="tut-num">${chapterNo}-${secNo}</span>${esc(sec.title)}</h3>
    <p class="tut-lead">${esc(sec.lead)}</p>
    ${sec.open ? `<p class="tut-open"><span class="tut-open-label">開き方</span>${esc(sec.open)}</p>` : ''}
    ${sec.can ? `<div class="tut-can"><div class="tut-can-title">この画面でできること</div><ul>${sec.can.map(x => `<li>${esc(x)}</li>`).join('')}</ul></div>` : ''}
    ${(sec.figures ?? []).map(renderFigure).join('')}
    ${(sec.steps ?? []).map(st => `<div class="tut-steps-block"><div class="tut-steps-title">${esc(st.title)}</div><ol class="tut-steps">${st.items.map(i => `<li>${esc(i)}</li>`).join('')}</ol></div>`).join('')}
    ${(sec.notes ?? []).map(n => `<div class="tut-${n.type}"><span class="tut-note-label">${n.type === 'tip' ? 'ヒント' : n.type === 'warn' ? '注意' : 'メモ'}</span>${esc(n.text)}</div>`).join('')}
  </div>`;
}

export function renderTutorialBody(): string {
  // 「やりたいことから探す」: 各節の tasks を章ごとにまとめる（一覧が長いので章の小見出しで区切る）
  const taskGroups = CHAPTERS.map(ch => {
    const links: string[] = [];
    ch.sections.forEach(sec => (sec.tasks ?? []).forEach(t => {
      links.push(`<a href="#sec-${sec.id}" class="tut-task"${sec.perm ? ` data-perm-key="${esc(sec.perm)}"` : ''}>${esc(t)}</a>`);
    }));
    return links.length ? `<div class="tut-task-group"><div class="tut-task-group-label">${esc(ch.label)}</div><div class="tut-tasks">${links.join('')}</div></div>` : '';
  }).join('');

  const toc = CHAPTERS.map((ch, ci) => `<div class="tut-toc-ch">
      <div class="tut-toc-section">第${ci + 1}章　${esc(ch.title)}</div>
      ${ch.sections.map((s, si) => `<a href="#sec-${s.id}"${s.perm ? ` data-perm-key="${esc(s.perm)}"` : ''}>${ci + 1}-${si + 1}. ${esc(s.title)}</a>`).join('')}
    </div>`).join('');

  const chapters = CHAPTERS.map((ch, ci) => `<div class="tut-chapter-wrap" id="ch-${ch.id}">
      <div class="tut-chapter"><div class="tut-chapter-label">第${ci + 1}章</div><h2>${esc(ch.title)}</h2></div>
      ${ch.intro ? `<p class="tut-intro">${esc(ch.intro)}</p>` : ''}
      ${ch.sections.map((s, si) => renderSection(s, ci + 1, si + 1)).join('')}
    </div>`).join('');

  return `
<div class="tut-cover">
  <div class="tut-cover-kicker">HOSHIKON USER GUIDE</div>
  <div class="tut-cover-title">ホシコン<br>かんたん使い方ガイド</div>
  <div class="tut-cover-sub">事務所・課長のみなさん向け　＋　乗務員のLINEの使い方</div>
  <div class="tut-cover-sub">最終更新: 2026年10月</div>
</div>

<div class="tut-find no-print">
  <div class="tut-find-title">やりたいことから探す</div>
  ${taskGroups}
  <label class="tut-search"><span>ことばで探す</span><input type="search" id="tut-search" placeholder="例: 忘れ物、シフト、印刷" autocomplete="off"></label>
  <div id="tut-search-empty" style="display:none;" class="tut-note">その言葉に当てはまる説明は見つかりませんでした。別の言い方で試してください。</div>
</div>

<div class="tut-toc">
  <h3>目次</h3>
  ${toc}
</div>

${chapters}

<div class="tut-footer">ホシコン かんたん使い方ガイド ｜ 分からないことは事務所のシステム担当まで</div>
`;
}
